def plain(t):
    t = re.sub("[\u0610-\u061A\u064B-\u0670\u06D6-\u06ED\u0640]", "", t)
    t = re.sub("[\u0623\u0625\u0622\u0671\u0621\u0624\u0626]", "\u0627", t).replace("\u0649", "\u064A").replace("\u0629", "\u0647")
    return re.sub("[^\u0621-\u064A]", "", t).replace("\u0627", "")


def main():
    quran = json.load(open(os.path.join(ROOT, "data", "quran-uthmani-quranenc.json"), encoding="utf8"))
    for les in L:
        out = []
        for s, a, w in les.pop("ex", []):
            words = quran[s - 1]["verses"][a - 1]["text"].split(" ")
            ks, want = [plain(x) for x in words], [plain(x) for x in w.split()]
            hit = None
            for i in range(len(ks) - len(want) + 1):
                if all(ks[i + k] and (ks[i + k] == want[k] or ks[i + k].endswith(want[k]) and len(ks[i + k]) - len(want[k]) <= 3)
                       for k in range(len(want))):
                    hit = i; break
            if hit is None:
                raise SystemExit(f"example not found: {s}:{a} {w}")
            out.append([s, a, hit, len(want)])
        if out: les["ex"] = out
        if "rule" in les: les["rule"] = RULES.index(les["rule"])
    path = os.path.join(ROOT, "web", "tajweed-lessons.js")
    with open(path, "w", encoding="utf8") as f:
        f.write("window.TAJWEED_LESSONS=" + json.dumps(L, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print(f"{len(L)} lessons, {sum(len(x.get('ex', [])) for x in L)} examples")


if __name__ == "__main__":
    main()
